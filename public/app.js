let currentLang = 'zh-TW';
const langOrder = ['zh-TW', 'zh-CN', 'en'];

function t(key) {
  return (i18n[currentLang] && i18n[currentLang][key]) || (i18n['zh-TW'][key]) || key;
}

function applyLanguage() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    var val = t(key);
    if (val) el.textContent = val;
  });
  document.getElementById('currentLangText').textContent = t('currentLangText');
  var dayIndex = new Date().getDay() % 7;
  var verseKeys = ['verse1', 'verse2', 'verse3', 'verse4', 'verse5', 'verse6', 'verse7'];
  var refKeys = ['verseRef1', 'verseRef2', 'verseRef3', 'verseRef4', 'verseRef5', 'verseRef6', 'verseRef7'];
  document.getElementById('verseText').textContent = t(verseKeys[dayIndex]);
  document.getElementById('verseRef').textContent = t(refKeys[dayIndex]);
}

function cycleLanguage() {
  var idx = langOrder.indexOf(currentLang);
  currentLang = langOrder[(idx + 1) % langOrder.length];
  applyLanguage();
  var msg = currentLang === 'zh-TW' ? '已切換至繁體中文' : currentLang === 'zh-CN' ? '已切换至简体中文' : 'Switched to English';
  showToast(msg);
}

