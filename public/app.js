function updateTime() {
  var now = new Date();
  var h = now.getHours(),
    m = now.getMinutes();
  h = h % 12 || 12;
  m = m < 10 ? '0' + m : m;
  document.getElementById('statusTime').textContent = h + ':' + m;
}
updateTime();
setInterval(updateTime, 30000);

var currentTab = 'home';
var isAdmin = false;

function switchTab(tab) {
  if (tab === 'admin' && !isAdmin) {
    showToast(t('toastLoginFail'));
    return;
  }
  currentTab = tab;
  document.querySelectorAll('.screen').forEach(function(s) {
    s.classList.remove('active');
  });
  document.getElementById('screen-' + tab).classList.add('active');
  document.querySelectorAll('.nav-item').forEach(function(n, i) {
    var tabs = ['home', 'sermons', 'docs', 'events', 'more'];
    n.classList.toggle('active', tabs[i] === tab);
  });
  document.getElementById('content').scrollTop = 0;
}

var toastTimer;

function showToast(msg) {
  var el = document.getElementById('toast');
  el.textContent = msg;
  el.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(function() {
    el.classList.remove('show');
  }, 2000);
}

function openYouTube(videoId) {
  showToast(t('toastOpeningYT'));
  setTimeout(function() {
    window.open('https://www.youtube.com/watch?v=' + videoId, '_blank');
  }, 300);
}

function filterSermons(btn, type) {
  document.querySelectorAll('.tab-btn').forEach(function(b) {
    b.classList.remove('active');
  });
  btn.classList.add('active');
  document.querySelectorAll('.sermon-item').forEach(function(item) {
    if (type === 'all' || type === 'recent') {
      item.style.display = '';
    } else {
      item.style.display = item.dataset.type === type ? '' : 'none';
    }
  });
}

